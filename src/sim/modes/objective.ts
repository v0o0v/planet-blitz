/**
 * 이 엔티티가 **무대 진행·승리 조건인 파괴 대상**인가. 참이면 자동 조준 대상이고 봇의 이동
 * 표적이 된다. 절차 청크 지형은 거짓이다(마커로 좁혔다).
 */
export function isObjectiveDestructible(e: Entity): boolean {
  // ⚠️ 추격 반격 장치(`isCounterDevice`)는 2026-08-05 재설계로 **배치 자체가 없어졌다**
  // (`modes/chase.ts` 상수 주석). 술어를 남겨 두면 어떤 엔티티도 만족하지 않는 죽은 분기가
  // 되고, 이 파일이 경고하는 "목록이 갈린다" 를 오히려 부른다 — 목록에서 뺀다. 추격의 목표는
  // 이제 파괴물이 아니라 **미확보 대피소**이고, 그 조준·추적은 파괴 대상이 아니므로 여기가
  // 아니라 봇 이동(`autopilot.ts nearestObjective`)이 따로 다룬다.
  // 촉매 목표물 등재(`catalyst/shared.ts` 의 `isCatalystObjective` 가 정본). **등재는 둘이다** —
  // `id 19` 광석 · `id 41` 관문. 둘 다 **부수는 것이 규칙**이고, `id 19` 는 *"그동안 자동 조준이
  // 그쪽에 묶인다"* 가 규칙 문장에 적힌 **대가**라 빼면 카드가 순수 이득이 된다.
  //
  // ⛔ `id 21` 결정 · `id 23` 씨앗/나무는 **일부러 뺐다**(`isCatalystEnemyOnlyObject`). 규칙이
  //    *"적이 밟으면"* 이라 파괴 주체가 적뿐인데, 이 게임은 수동 조준이 없어 등재하면 플레이어가
  //    자기 보상을 갉는 것을 **피할 방법이 없다**. 사유 전문은 그 술어 주석이 정본이다.
  //    되돌리려면 규칙 문장(`src/i18n/catalog.ts`)부터 고쳐라.
  // ⚠️ `id 47` 블록은 마커가 없다 — 블록 브레이크 벽은 `kind === 'wall'` 이라 이 틀 밖이다.
  // ⚠️ 여기를 채우는 레인은 **제외 쪽(`isCatalystShadow`)과 같이** 봐라 — 등재와 제외는 한 쌍이고,
  //    쌍 유지 3목록(조준 술어 · 충돌 격자 등록 · 아군탄 화이트리스트)을 하나만 고치면 무적
  //    차폐물이 된다(이 파일 헤더의 사고 4건이 그 부류다).
  return isContaminationNode(e) || isCatalystObjective(e);
}

/**
 * 이 무대의 진행·승리가 **목표 오브젝트 파괴**에 걸려 있는가(오염·추격).
 *
 * `isObjectiveDestructible` 이 "이 엔티티가 목표인가"라면 이쪽은 "이 무대가 목표 게이트형인가"다.
 * 둘을 같은 파일에 두는 이유는 **목록이 갈리면 안 되기 때문**이다 — 새 목표 게이트형 모드는
 * 두 술어에 동시에 들어와야 한다.
 */
export function isObjectiveGatedMode(mode: PlanetMode | undefined): boolean {
  return mode === PLANET_MODE.contamination || mode === PLANET_MODE.chase;
}

/**
 * 목표 게이트형 무대의 **피격 피해 배율**(1 미만 = 덜 아프다).
 *
 * ## 왜 이 축이 따로 필요한가 (2026-08-02 실측)
 * 이 무대들에서 **목표 총 HP 는 난이도와 페이싱을 동시에 정한다** — 노드·장치를 다 부수는 데
 * 걸리는 시간이 곧 ①얼마나 오래 버텨야 하는가 ②보스에 언제 닿는가 둘 다이기 때문이다. 그래서
 * 목표 HP 하나로는 "보스 도달 90초"(사용자 지시)와 "클리어율 60~80%"(ADR-0037)를 **함께
 * 만족시킬 수 없다.** 실측이 그대로 보여줬다:
 *
 * | 톡사르 노드 HP | 클리어율 | 보스도달 |
 * |---|---|---|
 * | 62,000 | 14.1% | 88.2s(목표 충족) |
 * | 40,000 | 24.5% | 74.9s(페이싱 파손) |
 *
 * 크라스(블록격파)만 밴드·페이싱을 동시에 잡았는데, 이유는 압사가 **진행 게이트가 아니라 순수
 * 피해원**이라 두 축이 애초에 분리돼 있어서다. 이 상수는 오염·추격에 **그 분리를 만들어 준다**:
 * 목표 HP 는 페이싱이 정한 값으로 되돌리고, 난이도는 생존 축이 진다.
 *
 * ## 왜 "적 유입"이 아니라 "피격 피해"인가
 * 유입 감소는 이 두 무대에서 **실측으로 기각**됐다(톡사르 14.3 → 13.9% · 니플헤임 30.6 → 31.7%,
 * 계수 1.6). 적은 압박인 동시에 젬·전리품을 내는 **성장 자원**이라 줄이면 굶는다. 피격 피해는
 * 성장에 손대지 않고 생존만 늘린다.
 *
 * ## 형태
 * `SHRINK_INTERVAL_SCALE` 과 같은 **모드 게이트 배율**이다. 다른 무대·침공은
 * {@link objectiveModeDamageScale} 이 1 을 돌려주므로 거동·해시가 **바이트 불변**이다.
 *
 * ## 왜 무대마다 값이 다른가
 * 같은 배율 0.5 를 둘에 걸었더니 **12.7pp 벌어졌다**(니플헤임 45.3% · 톡사르 26.8%). 두 무대는
 * 압박의 성질이 다르다 — 추격은 회피 가능한 단일 포식자 + 웨이브이고, 오염은 도망칠 수 없는
 * 영구 지형이 깔린 채 노드 10개를 도는 무대다. 그래서 하나의 값으로 둘을 맞출 수 없다.
 *
 * ## ⚠️ 이 축 **하나로도** 안 된다 — 손잡이는 셋이고 함께 움직여야 한다
 * 프로브 5회의 결론이다. 목표 HP 와 이 배율은 **페이싱을 서로 반대 방향으로 민다**:
 *
 * | 톡사르 조합 | 클리어율 | 보스도달 | 무엇이 깨졌나 |
 * |---|---|---|---|
 * | HP 62,000 · 배율 1.0 | 14.1% | 88.2s | 클리어율 |
 * | HP 40,000 · 배율 1.0 | 24.5% | 74.9s | 페이싱(빨라짐) |
 * | HP 62,000 · 배율 0.3 | 37.1% | 105.1s | 페이싱(느려짐) · 레벨업 10.1 |
 * | **HP 40,000 · 기울기 0.06 · 배율 0.26** | **61.7%** | **84.4s** | — |
 *
 * 세 번째 손잡이가 **단계 기울기**(`_HP_SLOPE`)다. 배율만 낮추면 플레이어가 안 죽는 대신
 * 고단계에서 목표를 못 깎아 **패배가 타임아웃으로 바뀐다** — 승률은 오르는데 구조 건전성이
 * 무너진다. 기울기가 그 고단계 격차를 담당한다.
 *
 * **셋 중 하나만 되돌리지 마라.** 각 상수 주석의 실측표가 서로를 전제한다.
 * TODO(밸런스): 출시 전 튜닝.
 */
export const CONTAMINATION_DAMAGE_SCALE = 0.26;

/** 추격(니플헤임)의 피격 피해 배율. 근거는 {@link CONTAMINATION_DAMAGE_SCALE}. */
export const CHASE_DAMAGE_SCALE = 0.32;

/**
 * 목표 오브젝트의 **조준 우선 가중치**(제곱거리에 곱한다. 1 = 우선권 없음, 작을수록 우선).
 * 단계 1 에서 {@link OBJECTIVE_AIM_BIAS_STAGE_1}, 단계 {@link OBJECTIVE_AIM_BIAS_STAGE_MAX_AT}
 * 이상에서 {@link OBJECTIVE_AIM_BIAS_STAGE_MAX} 로 선형 보간된다.
 *
 * ## 왜 필요한가 — 조준 목록에 있는 것으로는 부족하다 (2026-08-03 실측)
 * 이 파일 머리의 결함 4회는 전부 "목록에 없어서 **아예** 못 친다"였다. 이번 것은 그다음
 * 단계다: **목록에는 있는데 순번이 오지 않는다.** `nearestTarget` 은 사거리 안 최근접 하나를
 * 고르는데, 잡몹은 플레이어를 향해 몰려오므로 거의 항상 목표 오브젝트보다 가깝다. 단계가
 * 오를수록 수·밀도가 함께 늘어 그 확률이 1 에 수렴한다.
 *
 * 니플헤임 Lv100 타임아웃 런의 계측(`chaseDeviceHpFrac` 신설):
 *
 * | | 값 |
 * |---|---|
 * | 장치 잔여 HP 1.00(화력 0)인 런 | **0건** — 화력은 간다 |
 * | 5/5 잔존 런의 평균 잔여 HP | **0.766** — 300초에 23%만 깎았다 |
 * | 같은 셀 승리 런 | 83초에 5개 **전부** 파괴 |
 * | 타임아웃 런의 처치/초 | **6.12** (승리 런 3.11의 2배) |
 *
 * 화력이 약한 게 아니라 **전부 잡몹에 쓰고 있다.** 그래서 축은 HP 가 아니라 조준이다 —
 * 장치 HP 를 18% 깎아도 5/5 잔존이 34→31 로 안 움직였고, 1/10 로 만들어야 사라졌다.
 *
 * ## 왜 단계 함수인가
 * 고정 우선권은 **저단계를 깎는다**(니플헤임 Lv5 38% → 29%, 톡사르 27% → 23%): 잡몹이 적어
 * 우선권이 필요 없는 구간에서 코앞의 적을 두고 목표를 쏘다 죽는다. 문제 자체가 "단계가
 * 오를수록"이므로 처방도 단계를 타야 한다 — 단계 1 에서는 **정확히 1**(거동·해시 불변)이고
 * 고단계에서만 우선권이 붙는다.
 *
 * ## 형태
 * 순위 비교에만 곱하고 **사거리 판정에는 쓰지 않는다** — 할인된 거리로 사거리를 재면 탄이
 * 닿지 않는 표적을 조준하게 된다. 목표 오브젝트가 없는 무대(뱀서류·수축·레이싱·블록격파·
 * 침공)는 이 분기를 한 번도 타지 않으므로 거동·해시가 **바이트 불변**이다.
 * TODO(밸런스): 출시 전 튜닝.
 */
export const OBJECTIVE_AIM_BIAS_STAGE_1 = 1;
/** 고단계 우선 가중치(하한). 근거는 {@link OBJECTIVE_AIM_BIAS_STAGE_1}. */
export const OBJECTIVE_AIM_BIAS_STAGE_MAX = 0.1;
/** 이 단계 이상에서 {@link OBJECTIVE_AIM_BIAS_STAGE_MAX} 로 포화한다(만렙 = 단계 20). */
export const OBJECTIVE_AIM_BIAS_STAGE_MAX_AT = 20;

/**
 * 이 단계의 목표 오브젝트 조준 가중치. 단계 1 이하는 **정확히 1** 이라 호출부가 곱해도
 * 값이 바뀌지 않는다(저단계 거동 완전 불변).
 */
export function objectiveAimBias(stage: number): number {
  if (stage <= 1) return OBJECTIVE_AIM_BIAS_STAGE_1;
  if (stage >= OBJECTIVE_AIM_BIAS_STAGE_MAX_AT) return OBJECTIVE_AIM_BIAS_STAGE_MAX;
  const t = (stage - 1) / (OBJECTIVE_AIM_BIAS_STAGE_MAX_AT - 1);
  return OBJECTIVE_AIM_BIAS_STAGE_1 + (OBJECTIVE_AIM_BIAS_STAGE_MAX - OBJECTIVE_AIM_BIAS_STAGE_1) * t;
}

/**
 * 이 런의 피격 피해 배율. 목표 게이트형 무대 외에는 **정확히 1** 이다 — 호출부가 그 경우
 * 한 줄도 실행하지 않도록 `=== 1` 로 가드한다(기존 해시 완전 불변).
 */
export function objectiveModeDamageScale(mode: PlanetMode | undefined): number {
  if (mode === PLANET_MODE.contamination) return CONTAMINATION_DAMAGE_SCALE;
  if (mode === PLANET_MODE.chase) return CHASE_DAMAGE_SCALE;
  return 1;
}
