/**
 * **적 밀도 패스** — "적과 탄은 30% 더, 난이도는 그대로" (사용자 결정 2026-08-08).
 *
 * ## 무엇을 요청받았는가
 * 사용자 요청 그대로다: *"적들이 지금보다 30% 정도 더 많이 나왔으면 좋겠고 적들의 탄환이
 * 지금보다 30% 정도 더 많았으면 좋겠어. 그런 상태로 난이도가 비슷하게 유지 됐으면 좋겠어."*
 *
 * 즉 이것은 **난이도 변경이 아니라 화면 밀도 변경**이다. 두 축(적 수·탄 수)을 올리고, 그
 * 상승분이 플레이어에게 가하는 압력을 **보상 축으로 되돌린다**.
 *
 * ## 왜 데이터가 아니라 여기인가
 * 적 스탯은 `data/enemies.ts` 와 `data/planets/*.ts` 에 행성별로 수십 개가 흩어져 있다.
 * 30% 를 손으로 곱하면 (a) 누락이 조용히 생기고 (b) 원본 저작값이 사라져 다음 사람이 "이게
 * 원래 값인지 밀도 패스가 곱한 값인지" 를 영영 알 수 없다. `PVE_DENSITY_MULT`(`waves.ts`)가
 * 이미 같은 이유로 원본 `SEGMENTS` 를 안 건드리고 소비 지점에서 곱하는 방식을 쓴다 —
 * 이 모듈은 그 관용구를 네 축으로 확장한 것이다.
 *
 * **원본 저작값은 그대로 둔다.** 여기 계수를 전부 1 로 되돌리면 거동이 패스 이전과 같다.
 *
 * ## 축 넷과 그 짝 (⚠️ 짝을 깨면 난이도가 움직인다)
 *
 * | 올리는 축 | 배수 | 되돌리는 짝 | 배수 |
 * |---|---|---|---|
 * | 적 수 | {@link ENEMY_COUNT_MULT} 1.3 | 적 HP | {@link ENEMY_HP_MULT} 1/1.3 |
 * | 적 발사 빈도 | {@link ENEMY_FIRE_RATE_MULT} 1.3 | (실측 결과 **불필요**) | — |
 *
 * · **적 수 ↔ 적 HP**: 총 적 HP 풀이 보존된다(`1.3 × 1/1.3 = 1`). 그래서 세그먼트를 밀어내는
 *   데 드는 총 화력, 곧 **클리어 속도가 그대로**다. 처치 수만 30% 는다.
 * · **발사 빈도에는 짝을 걸지 않았다 — 실측이 그렇게 말했다.** 처음에는 탄 유입이 두 축의
 *   곱(`1.3 × 1.3 = 1.69`)으로 늘 테니 피해를 `1/1.69 ≈ 0.6` 으로 내려야 한다고 **계산해서**
 *   그렇게 넣었다. 재 보니 틀렸다 — 그 값에서 초당 피격량이 40 → 23.5 로 **40% 쉬워졌다.**
 *   적 HP 짝이 이미 되돌리고 있었기 때문이다: 적이 1.3배 빨리 죽으니 개체당 발사 횟수가
 *   그만큼 줄어 탄 유입 증가분이 상쇄된다. 계산으로 넣은 보상이 **이중 보상**이었다.
 *   ⚠️ 계측기를 두고 이론값을 박는 것은 이 리포가 반복해 온 실패다. 이 문단을 지우지 마라.
 *
 * ## 부작용 하나 — 경제 (그리고 그 짝)
 * 처치가 30% 늘면 젬 XP 도 30% 는다. 밀도 요청에 경제 인플레가 딸려 오면 안 되므로
 * {@link ENEMY_XP_MULT} 로 되돌린다. **전리품 드랍은 되돌리지 않았다** — 드랍은 엘리트·보스
 * 기반이고(`rollEliteDrop`/`rollBossDrop`) 엘리트 수는 `eliteCount`(밴드 데이터)가 정해 이
 * 패스가 건드리지 않기 때문이다.
 *
 * ## 이 패스가 닿지 않는 것
 * **보스**다. 보스는 `boss.ts` 의 자체 사격 루프를 돌고 웨이브 밀도 축 밖에 있다. 의도한
 * 것이다 — 보스는 한 기뿐이라 "30% 더 많이" 가 정의되지 않고, HP 를 1/1.3 로 깎으면 보상 없는
 * 순수 약화가 된다.
 *
 * ⚠️ **침공(`invasion3`)은 "무관"이 아니다 — 축마다 다르다**(정정 2026-08-08). 여기 한때
 * *"침공도 절차 생성 웨이브를 안 돌리므로 무관하다"* 라고 적혀 있었는데, 그 한 줄이 세 축을
 * 뭉뚱그렸다. 실제 소비 지점을 세면:
 *  · **적 수·적 HP·젬 XP** — `spawnEnemy`/웨이브 경로에만 있어 침공에 **안 걸린다**(맞다).
 *  · **발사 빈도**({@link ENEMY_FIRE_RATE_MULT}) 와 **해저드 주기**({@link HAZARD_RATE_MULT}) —
 *    `summonEnemy` 도 `scaledFireCooldown` 을 부르므로 침공 편대원·스포너 드론에 **걸린다.**
 *    전수 실측은 `HAZARD_RATE_MULT` 주석 §침공에는 걸린다 에 있다.
 *
 * ⚠️ **밀도 축이 안 닿는다는 것이지 이 파일이 보스를 안 만진다는 뜻은 아니다** —
 * {@link BOSS_HP_MULT} 는 별개 축으로 이 모듈에 함께 산다(같은 "적 스케일" 계열이라 여기
 * 두지만, 위 네 축의 짝 관계와는 무관하다).
 *
 * ## 결정론
 * 전부 기존 float 곱 경로에 얹는다(`catalystMods.enemyHp` 와 같은 자리·같은 성질). 쿨다운만
 * 정수 눈금이라 `Math.round` 로 접고 하한 1 을 건다 — 0 이 되면 매 틱 발사가 되어 축이 폭주한다.
 * `Math.random`·`Date.now` 를 쓰지 않는다.
 *
 * ⚠️ **PvE 골든은 이 값들에 걸려 있다.** 고치면 `tests/pilotFrameFreeze.test.ts` 가 먼저 빨개진다.
 */

import { stageDamageMult } from '../../data/waves.js';

/**
 * 적 **수** 배수. 웨이브 유입·온스크린 상한 **양쪽**에 걸린다 — 한쪽만 걸면 상한이 유입을
 * 막거나(밀도가 안 오른다) 유입이 상한을 못 채운다(상한이 무의미해진다).
 *
 * `PVE_DENSITY_MULT`(1.5) 위에 곱해진다. 그 상수를 직접 1.95 로 고치지 않는 이유는 두 값의
 * **출처가 다르기** 때문이다 — 1.5 는 클리어율 실측으로 정해진 밸런스 상수이고, 1.3 은 사용자의
 * 화면 밀도 요청이다. 곱해 두면 다음 사람이 어느 쪽을 되돌려야 하는지 알 수 있다.
 */
export const ENEMY_COUNT_MULT = 1.3;

/**
 * 적 **발사 빈도** 배수. 쿨다운을 이 값으로 **나눈다**(빈도 1.3배 = 주기 1/1.3).
 *
 * ## 왜 발사 주기인가 (탄 수 축의 선택)
 * "탄이 30% 더" 를 만드는 손잡이는 둘이다 — 볼리당 탄 수(`attack.count`)와 발사 주기.
 * 전자는 **일부 공격에만 있다**(`mortar`·`lava` 는 `count` 가 없다). 주기는 모든 공격 종류가
 * 공유하므로 축이 균일하게 오른다. 그리고 볼리 크기를 키우면 *"한 번에 피할 수 없는 탄막"* 이
 * 되어 밀도가 아니라 난이도가 오른다 — 요청은 밀도다.
 */
export const ENEMY_FIRE_RATE_MULT = 1.3;

/**
 * 적 **HP** 배수 = `1 / ENEMY_COUNT_MULT`. 총 적 HP 풀 보존이 계약이므로 리터럴로 적지 않고
 * 짝에서 파생한다 — 한쪽만 고쳐 짝이 조용히 깨지는 것을 구조적으로 막는다.
 *
 * ## ⚠️ 거는 자리는 **웨이브 경로 하나뿐**이다 (`waves.ts` `spawnEnemy`)
 * 짝인 {@link ENEMY_COUNT_MULT} 가 걸리는 곳이 거기뿐이기 때문이다. **`summonEnemy` 에는 걸지
 * 않는다** — 그 함수의 호출자(침공 드론 스포너·침공 편대·보스 무리·중반 격전·촉매 소환·조우
 * 수호)는 개수를 자기가 정하므로 HP 만 깎으면 보상 없는 순수 약화가 된다. 밀도 패스 초판이
 * 실제로 그 상태였고 `tests/invasionFacility.test.ts` 가 드론 내구도 75 → 57 로 잡았다.
 * 사유 전문은 `waves.ts` `summonEnemy` 본문 주석에 있다.
 */
export const ENEMY_HP_MULT = 1 / ENEMY_COUNT_MULT;

/**
 * 젬 **XP** 배수 = `1 / ENEMY_COUNT_MULT`. 처치가 30% 늘어도 런당 XP 가 그대로이도록 되돌린다
 * (위 §부작용 하나). {@link ENEMY_HP_MULT} 와 같은 사유로 짝에서 파생한다.
 */
export const ENEMY_XP_MULT = 1 / ENEMY_COUNT_MULT;

/**
 * 적 **피해**(접촉·탄·해저드 공통) 배수 — 지금은 **1.0(무보상)** 이고, 그것이 실측 결론이다.
 *
 * ## 실측 (`bench/incomingDps.ts` · 무장비 스트라이커 · 행성 0 · 시드 6개 · 5400틱)
 * 눈금은 **선체가 초당 잃는 HP**. 세 조건을 교환 대조했다:
 *
 * | 조건 | Lv5 | Lv50 | Lv100 |
 * |---|---|---|---|
 * | 패스 이전(계수 전부 1) | 39.80 | 40.53 | 39.24 |
 * | 밀도 패스 · 이 값 **1.0** | **39.02** | **40.00** | **40.09** |
 * | 밀도 패스 · 이 값 0.6(초판 이론값) | 23.46 | 24.00 | 24.05 |
 *
 * 즉 **적 HP 짝만으로 압력이 보존된다.** 1.0 이 정답이고 0.6 은 40% 완화였다.
 * 계수를 전부 1 로 되돌린 대조군이 패스 이전 값을 그대로 재현했다 — 계측기가 이 축만 보고
 * 있다는 증거다(교환 대조를 재생성보다 **먼저** 했다).
 *
 * ## ⚠️ 그래도 이 손잡이를 남겨 둔 이유 — 봇과 사람은 다르게 맞는다
 * 위 계측의 파일럿은 **카이팅**한다(최근접 적과 거리 유지). 사람은 탄막을 통과하며 논다.
 * 탄이 46% 늘어도 봇의 피격량이 안 움직인 것은 *"탄이 위협이 아니다"* 가 아니라 *"이 파일럿이
 * 원래 탄에 잘 안 맞는다"* 일 수 있고, 그 구분은 봇으로는 못 한다 — ADR-0051 이 절대 난이도를
 * 사람에게 맡긴 바로 그 사유다.
 *
 * 그래서 사람이 "더 어려워졌다" 고 하면 **여기를 내린다.** 값을 바꾸면 위 표를 다시 뜨고 함께
 * 갱신하라 — 이 상수는 계산이 아니라 실측으로만 정한다.
 */
export const ENEMY_DAMAGE_MULT = 1.0;

/**
 * 이 런의 **적 피해 총 배수** = {@link ENEMY_DAMAGE_MULT} × 단계 곡선(`stageDamageMult`).
 * 적 피해를 곱하는 자리는 **전부 이 함수를 통과해야 한다** — 소비 지점이 여섯이고 그 중
 * `summonEnemy` 하나가 침공 경로다.
 *
 * ## ⚠️ 침공 게이트가 여기 있다 — 단계로는 못 막는다
 * 침공은 `config.stage` 가 **1** 이라 «단계 1 은 배수 1» 규약에 기대는 축(`stageHpMult`)은
 * 자동으로 안전하지만, 단계 피해 곡선은 단계 1 이 **2.0** 이다. 그래서 게이트를 `invasion3`
 * 유무에 건다 — 침공에서는 정확히 `ENEMY_DAMAGE_MULT` 만 남아 **거동·해시가 바이트 불변**이다.
 *
 * `WorldState` 대신 **구조적 최소 타입**을 받는다 — 이 모듈은 import 가 0 개인 순수 상수
 * 모듈이고, `world.ts` 를 끌어오면 순환이 된다.
 */
export function enemyDamageScale(config: {
  readonly stage?: number;
  readonly invasion3?: unknown;
}): number {
  if (config.invasion3 !== undefined) return ENEMY_DAMAGE_MULT;
  return ENEMY_DAMAGE_MULT * stageDamageMult(config.stage ?? 1);
}

/**
 * 세그먼트 동시 적탄 상한 배수 = 탄 유입 증가분(`적 수 × 발사 빈도`).
 *
 * ## ⚠️ 이것이 없으면 30% 가 **조용히 잘린다**
 * `spawnEnemyBullet` 경로는 전부 `state.enemyBulletCount >= state.bulletCap` 에서 **break** 한다
 * — 예외도 경고도 없이 그냥 안 쏜다. 상한을 그대로 두고 유입만 1.69배로 올리면 화면 탄 수는
 * 상한에서 평평해지고, 사용자는 "30% 늘려 달랬는데 안 늘었다" 를 보게 된다. 이 저장소가 반복
 * 겪은 「조용한 미발현」의 정확한 형태다.
 */
export const ENEMY_BULLET_CAP_MULT = ENEMY_COUNT_MULT * ENEMY_FIRE_RATE_MULT;

/**
 * **보스 HP** 배수 — 2.0 = 지금의 두 배 (사용자 결정 2026-08-08).
 *
 * ## 왜 필요해졌는가
 * 같은 플레이테스트 루프에서 플레이어 공격력이 8 → 12.75 로 **누적 +59.4%** 올랐다
 * (`world.ts` `DEFAULT_WEAPON` 위 §기체 기본 스탯 상향). 잡몹 쪽은 밀도 패스의 적 HP 짝이
 * 함께 움직였지만 **보스는 그 짝 밖**이라(위 §이 패스가 닿지 않는 것) 보스전만 일방적으로
 * 짧아졌다. 사용자가 그것을 보고 두 배를 지시했다.
 *
 * ## 왜 `data/bosses/*.ts` 의 `hp` 를 직접 안 고치는가
 * 보스 정의가 **9개**다(행성 6 + 의뢰 3). 손으로 두 배를 곱하면 (a) 누락이 조용히 생기고
 * (b) 원본 저작값이 사라진다 — 이 모듈이 처음부터 쓰는 논리 그대로다. 소비 지점이 정확히
 * **둘**(`world.ts` 의 보스 스폰 · `modes/chase.ts` 의 포식자)이라 곱할 자리가 좁다.
 *
 * ## ⚠️ 두 스폰 지점에 **함께** 걸어야 한다
 * 추격 모드의 포식자는 별도 개체가 아니라 **그 무대의 보스 그 자체**다(취약화 뒤가 곧
 * 보스전이고 `stepBoss` 가 두 번째 보스를 안 세운다). 한쪽만 걸면 같은 보스가 무대에 따라
 * HP 가 달라지고, 그 어긋남은 화면에 아무 흔적을 안 남긴다.
 *
 * 의뢰 보스 3종에도 함께 걸린다 — 소비 지점이 같은 한 줄이기 때문이고, "보스" 라는 요청
 * 문면과도 맞는다.
 */
export const BOSS_HP_MULT = 2.0;

/**
 * **보스 HP 의 단계 곡선** — `stage` 가 깊어질수록 보스가 두꺼워진다 (사용자 결정 2026-08-08).
 *
 * ## 무엇이 신고됐나
 * *"보스의 HP가 낮아서 10단계와 20단계에서 테스트 했을 때 너무 빨리 죽었어. 거의 3초안에
 * 죽은거 같아. 30초 정도는 버틸 수 있게 수정해줘."*
 *
 * ## 원인 — 보스만 단계 배율 밖에 있었다
 * 잡몹 HP 에는 `stageParams(stage).hpMult` 가 걸린다(`waves.ts` `spawnEnemy`). **보스에는 안
 * 걸려 있었다.** 그래서 보스 HP 가 단계 1 이든 20 이든 **7,200 으로 고정**인데 플레이어 화력만
 * 레벨을 따라 올라가, 깊은 단계일수록 보스전이 일방적으로 짧아졌다. 실측(`bench/bossTtk.ts`,
 * 스트라이커·카르곤·표준 빌드):
 *
 * | 단계 | Lv | 보스 maxHp | TTK 중앙 |
 * |---|---|---|---|
 * | 10 | 50 | 7,200 | **4.0초** |
 * | 20 | 100 | 7,200 | **3.3초** |
 *
 * 사용자 체감("거의 3초")과 계측이 일치한다.
 *
 * ## ⚠️ 왜 잡몹 곡선(`stageHpMult`)을 그대로 쓰지 않는가 — 모양이 다르다
 * 그 곡선은 단계 10 에서 **×14.5**, 단계 20 에서 **×80.8** 이다. 잡몹 곡선이 그렇게 가파른
 * 것은 잡몹이 «여러 마리가 동시에 압박을 만드는» 축이기 때문이고, 보스는 «한 기와 얼마나 오래
 * 싸우는가» 라 눈금이 다르다.
 *
 * ⚠️ 이 절이 한때 *"보스에 그대로 걸면 단계 20 TTK 가 약 267초"* 라고 적고 있었다. **그
 * 숫자는 죽었다**(레벨 무관 전제 위의 값이다) — 지금 같은 계산을 하면 **48.4초**이고, 더
 * 중요한 것은 그 곡선이 깊은 단계에서 **TTK 를 되레 줄인다**는 점이다. 아래 §잡몹 곡선과의
 * 관계가 뒤집혔다 를 보라.
 *
 * ## ⭐ 눈금은 **사용자의 실측 두 점**이다 — 리포 안 계측기 둘은 사람과 갈렸다
 * 이 상수를 정하며 계측기를 두 개 만들었고 **둘 다 사람 눈금과 갈렸다.** 그 사실을 남긴다,
 * 다음 사람이 같은 함정에 다시 들어가지 않도록.
 *
 * | 눈금 | 단계10 실효DPS | 단계20 실효DPS | 왜 갈리는가 |
 * |---|---|---|---|
 * | **사용자 실측**(HP 7,200 에서 «거의 3초») | **≈2,400** | **≈2,400** | — (정본) |
 * | `bench/gearDps.ts` 더미 반경 40 | 1,692 | 2,198 | 표적이 작아 산탄이 빗나간다 |
 * | `bench/gearDps.ts` 더미 반경 128(보스 크기) | 1,821 | 4,684 | 시드별 장비 롤이 764~34,604 |
 * | `bench/bossTtk.ts` 봇 실전 | 3,999 | 8,888 | 내구+접촉 파일럿이 사람보다 세게 때린다 |
 *
 * · **더미 반경이 주 변수였다.** 초판 계측기는 반경 40(잡몹 크기)으로 재서 보스전 화력을 4배
 *   과소평가했다 — 무기가 `spread` 로 흩뿌리는 탄이 작은 표적에선 대부분 빗나가고 보스는
 *   커서 거의 다 맞는다. 표적 크기는 부수 조건이 아니라 **화력 계측의 주 변수**다.
 * · **봇 TTK 는 사람보다 짧다.** `contactPilotInput` 은 적에 붙어 조향하고 내구 파일럿은
 *   회피할 이유가 없어 **가동률이 사람보다 높다.** 이 파일에 한때 "봇 눈금은 하한(TTK 가
 *   실제보다 길다)" 이라고 적었는데 **그것은 틀렸다** — 부호가 반대다.
 *
 * ⇒ 그래서 1·2차 판의 곡선은 **사용자가 직접 잰 두 점** 위에 세웠다: `7,200 / 3초 = 2,400 DPS`.
 * ⚠️ 이 눈금에서 **«레벨과 무관하다» 는 부분은 3차(아래)에 죽었다.** 값 2,400 자체는 살아
 * 있고, 이제 **Lv1 기준 DPS** 로 읽는다.
 *
 * ## 왜 구간선형이 아니라 **지수**인가 (사용자 결정 2026-08-08, 2차)
 * 1차 판은 `stageHpMult` 와 같은 구간선형(앵커 1 / 10 / 11)이었고 단계 20 이 ×10.9 였다.
 * 사용자가 그것을 보고 지시했다: *"보스 hp 증가 그래프를 지금 20단계 보스가 현재보다 두배
 * 올라가는 수준으로 바꿔줘"* → *"단계1은 현재 값으로 고정하고 그 뒤로 어느정도 지수적으로
 * 올라가서 20단계가 두배가 되도록"*.
 *
 * 그래서 형식을 바꿨다 — **단계 1 을 1 로 고정한 등비수열**이다. 2차 판의 공비는 «단계 20 =
 * 21.8(=1차 판 10.9 의 두 배)» 하나로 결정돼 `21.8^(1/19) ≈ 1.1761` 이었다.
 * **형식은 그대로 살아 있고, 공비만 3차에 다시 정했다.**
 *
 * ## ⭐ 3차 (2026-08-08) — **값보다 근거가 먼저 죽었다**
 * 2차 판의 공비는 *"플레이어 화력은 레벨과 무관하다"* 는 — **당시엔 참이었던** — 전제 위에
 * 서 있었다. PR#399 (`src/items/loadout.ts` `PILOT_LEVEL_GROWTH_PER_LEVEL` = 1.0164, 피해·HP
 * 두 축에 레벨당 등비)가 그 전제를 깼다. 단계당으로 접으면 **×1.0847 = √1.1761** 이라, 보스
 * 곡선이 매 단계 벌어 놓은 것의 **로그 기준 절반을 플레이어가 도로 가져간다.**
 *
 * | 단계(Lv) | 2차 판이 의도한 TTK | PR#399 이후 실제 |
 * |---|---|---|
 * | 10 (Lv50) | 12.9초 | **5.8초** |
 * | 20 (Lv100) | 65.4초 | **13.1초** |
 *
 * ⇒ 사용자 결정: **단계 20 을 65초로 되돌린다.** 고칠 자리는 PR#399 의 공비가 아니라(사용자가
 * 승인해 머지한 값이다) 이 상수다.
 *
 * ## ⭐ 새 눈금은 **레벨-연동 DPS** 다 — 「레벨 무관 한 점」은 더 이상 눈금이 아니다
 * `실효DPS(단계 s) = 2,400 × 1.0164^(5s − 1)` (단계 s 의 표준 레벨이 `5s` 다 —
 * `LEVEL_PER_STAGE`). `bench/gearLevelCurve.ts` 가 같은 식을 쓴다(PR#399 레인의 계측기다).
 * 이 눈금에서 «단계 20 = 65초» 를 풀면 **단계 20 배수 ×108.4 → 공비 1.2797** 이다.
 *
 * 후보 비교(같은 눈금 · TTK 초 · 2026-08-08 실측):
 *
 * | 공비 | 단계1 | 단계5 | 단계10 | 단계15 | 단계20 | 단계25 |
 * |---|---|---|---|---|---|---|
 * | 1.1761 (2차 판) | 2.8 | 3.9 | 5.8 | 8.7 | 13.1 | 19.6 |
 * | 1.2334 (30초 안) | 2.8 | 4.7 | 8.9 | 17.0 | 32.3 | 61.3 |
 * | **1.2797 (채택)** | **2.8** | **5.4** | **12.4** | **28.4** | **65.0** | **148.5** |
 * | 1.2806 | 2.8 | 5.5 | 12.5 | 28.7 | 65.9 | 151.0 |
 *
 * | 단계 | 배수 | 카르곤 보스 HP |
 * |---|---|---|
 * | 1 | 1.000 | 7,200 |
 * | 5 | 2.682 | 19,309 |
 * | 10 | 9.204 | 66,268 |
 * | 15 | 31.587 | 227,430 |
 * | 20 | **108.406** | **780,527** |
 *
 * ⭐ **한 점을 맞춘 것이 아니라 곡선 전체가 복원된다.** `1.2797 ≈ 1.1761 × 1.0847` 이다 — 새
 * 공비는 «옛 공비 × 레벨 성장의 단계당 공비» 이고, 그래서 단계 10 의 TTK 도 12.9 → **12.4초**
 * 로 PR#399 **이전 값**에 돌아온다(단계 20 은 65.4 → 65.0). 우연이 아니라 구조다: TTK 의
 * 단계당 비가 `공비 ÷ 레벨성장^5` 이므로, 레벨 성장을 공비에 곱하면 TTK 곡선이 그대로 선다.
 * ⇒ **다음에 `PILOT_LEVEL_GROWTH_PER_LEVEL` 이 움직이면 이 상수도 같은 배수로 따라가야 한다.**
 *
 * ## ⚠️ 2차 판이 남긴 «중간 단계가 얇다» 경고는 3차로 해소됐다
 * 2차 판의 단계 10 은 ×4.31 로 1차 판(구간선형 ×9.1)의 절반 아래였고, 그 절이 *"얇게 느껴지면
 * 고칠 자리는 형식이 아니라 공비"* 라고 적어 두었다. 3차 공비에서 단계 10 이 **×9.20** 이라
 * 1차 판을 넘어섰다 — 그 처방대로 형식을 그대로 두고 공비만 움직여 해소된 것이다.
 *
 * ## ⚠️ 잡몹 곡선과의 관계가 **뒤집혔다** — 단계 19 부터 보스 배수가 더 크다
 * 2차 판은 교차가 단계 33 이었고 이 파일이 *"실플레이 구간에서는 보스가 잡몹의 1/3 아래"* 라고
 * 적고 있었다. 3차 공비에서 교차는 **단계 19** 다(단계 20 은 보스 108.4 > 잡몹 80.8).
 *
 * **그래도 잡몹 곡선은 더 이상 상한이 아니다** — 그 비교의 전제도 PR#399 가 깼다. 잡몹 곡선을
 * 보스에 그대로 걸면 TTK 가 단계 20 에서 **48.4초**로 목표에 못 미치고, 그보다 나쁜 것은
 * **단계 25 46.6초 · 단계 30 40.6초로 되레 줄어든다**는 점이다 — 잡몹 곡선은 구간선형인데
 * 플레이어 화력은 지수라 깊은 단계에서 반드시 화력이 이긴다. ⇒ **보스전 길이가 단계를 따라
 * 자라려면 곡선이 지수여야 하고, 공비가 레벨 성장의 단계당 공비(1.0847)보다 커야 한다.**
 * `tests/bossStageHp.test.ts` 가 그 부등식을 잠근다 — 옛 «잡몹보다 완만하다» 단언을 대체했다.
 *
 * ## ⚠️ 왜 `Math.pow` 가 아니라 반복 곱인가 — 결정론
 * `Math.pow`/`**` 는 IEEE-754 가 **정확 반올림을 요구하지 않는** 연산이라 엔진·플랫폼에 따라
 * 마지막 비트가 갈릴 수 있다. 이 값은 적 HP 로 들어가 `hashWorld` 에 접히므로 그 갈림이 곧
 * 리플레이·골든 불일치다. 그래서 **리터럴 공비를 정수 번 곱한다** — 곱셈은 IEEE 정확 반올림이
 * 보장되어 어디서 돌려도 비트 동일이다. `src/sim/**` 이 `Math.pow` 를 한 번도 안 쓰는 것도
 * 같은 이유다(실측: 리포 전체에서 `Math.pow` 는 render·harness·bench 에만 있다).
 * ⇒ **공비를 `108.4 ** (1/19)` 로 계산해서 쓰지 마라.** 리터럴이어야 한다.
 *
 * ## ⚠️ 단계 1 은 정확히 1 이다 — 두 가지 이유로 불변이다
 *  ① **사용자가 이미 판정했다.** Lv1 단계1 런은 *"보스를 25% 남기고 사망"* 이었고 그것이 이
 *     레인의 공격력 확정 근거였다. 여기를 건드리면 **사용자가 좋다고 한 지점을 되돌리는 것**이다.
 *     이번 2차 지시에서도 *"단계1은 현재 값으로 고정"* 으로 다시 확인됐다.
 *  ② **골든 기준 무대다.** `stageHpMult` 가 같은 사유로 단계 1 에 early-return 을 두고 있다.
 *
 * ## ⚠️ 봇 실측은 목표보다 짧게 나온다 — 그것이 정상이다
 * `bench/bossTtk.ts` 는 봇이 사람보다 2~4배 세게 때려(위 표) 사용자 눈금보다 짧은 TTK 를
 * 낸다. **그 숫자를 보고 "목표 미달"이라며 공비를 또 올리지 마라** — 봇에 맞추면 사람에게는
 * 몇 배짜리 보스가 된다. 판정은 사람이 한다.
 *
 * ⚠️ **이 값은 재플레이로 확인해야 한다.** 근거가 사용자의 눈대중 "거의 3초" 한 점(× 레벨
 *   성장 모델)이라 ±로 흔들린다. **리포 안 어떤 계측기도 이 축을 대신 확인해 주지 못한다** —
 *   위 표가 그 이유다.
 */
const BOSS_HP_ANCHOR_STAGE_1 = 1; // **불변** — 사용자 판정 지점 + 골든 기준 무대(위 §⚠️).

/**
 * 단계당 공비. **리터럴이어야 한다**(위 §결정론 — `108.4 ** (1/19)` 로 계산하지 마라).
 *
 * `1.2797^19 ≈ 108.45` → 레벨-연동 DPS 눈금에서 **단계 20 TTK ≈ 65초**다(위 §새 눈금).
 * 읽는 법: `1.2797 ≈ 1.1761 × 1.0847` = «2차 판 공비 × 레벨 성장의 단계당 공비» — 그래서
 * TTK 곡선이 PR#399 이전 모양 그대로 선다.
 * 이 값을 바꾸면 전 단계가 함께 움직이므로 `tests/bossStageHp.test.ts` 의 실값 단언이 먼저 알려 준다.
 */
const BOSS_HP_GROWTH_PER_STAGE = 1.2797;

/**
 * 반복 곱의 상한 지수. **밸런스 값이 아니라 루프 가드**다 — 도전 가능 단계는 원리적으로 무한히
 * 깊어질 수 있고(`stageOpenCap`), 지수 곡선에 그 값을 그대로 태우면 반복 횟수가 입력을 따라
 * 무한히 는다. 200 은 실플레이에서 도달할 수 없는 깊이다(그 지점 배수가 이미 약 1.1e14).
 */
const BOSS_HP_MAX_EXPONENT = 200;

/**
 * 보스 HP 단계 배수 — 단계 1 을 1 로 고정한 **등비수열**. 위 상수 주석이 정본이다.
 * **정수 in / 실수 out**(호출부가 반올림한다).
 *
 * 단계 1 은 앵커 상수를 그대로 돌려준다(early-return) — 곱을 한 번도 안 돌아야 골든 기준
 * 무대의 값이 **정확히** 1 이다(`stageHpMult` 와 같은 규율).
 */
export function bossStageHpMult(stage: number): number {
  if (stage <= 1) return BOSS_HP_ANCHOR_STAGE_1;
  const n = stage - 1 < BOSS_HP_MAX_EXPONENT ? stage - 1 : BOSS_HP_MAX_EXPONENT;
  let m = BOSS_HP_ANCHOR_STAGE_1;
  // ⚠️ 반복 곱이다(`Math.pow` 금지 — 위 §결정론). 곱셈만 쓰므로 어디서 돌려도 비트 동일이다.
  for (let i = 0; i < n; i++) m *= BOSS_HP_GROWTH_PER_STAGE;
  return m;
}

