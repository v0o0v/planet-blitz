/**
 * **`id 27 afterburner`(애프터버너)** — 최대 HP 원장 + 대기 전리품, **한 칸에 접어서**.
 *
 * ## 왜 원장이 필요한가 — 되돌림이 이득으로 뒤집히는 것을 막는다
 * 카드는 *"대시마다 최대 HP 가 3 깎이고, 대시로 관통해 죽이면 3이 돌아온다"* 인데, **대시 한
 * 번이 여러 적을 관통할 수 있다.** 되돌림을 무조건 `+3` 으로 두면 한 대시에 둘을 잡는 순간
 * 최대 HP 가 **출발값을 넘어** 대가가 순이득으로 뒤집힌다. 그래서 "지금까지 실제로 깎인 양"을
 * 들고 그 범위 안에서만 되돌린다(`ChainReactionSlot.MaxHpCut` 과 같은 형태·같은 사유).
 *
 * ## 왜 대기 전리품이 같은 칸에 있는가
 * *"관통 처치는 전리품을 확정으로 뱉는다"* 의 스폰 지점이 앵커 밖이다 — 처치를 관측하는
 * `onEnemyDamagedCatalyst` 는 `for (const b of state.entities)` **순회 안**이라 훅에서 스폰이
 * 금지돼 있다. 그래서 개수만 세어 두고 다음 틱 `powerOnTick`(순회 밖)에서 낳는다.
 * 예비 칸이 **하나뿐**이라 두 값을 비트로 접었다(폭을 늘리면 골든이 전량 재생성 대상이다 —
 * 헤더 §24 의 근거).
 *
 * ## 인코딩 — `cut * 16 + pending`
 * `pending` 은 하위 4비트(0..15)로 **포화**시킨다. 넘치는 분을 상위로 흘리면 그 순간 원장이
 * 조용히 부풀어 최대 HP 가 늘어난다 — 전리품을 몇 장 놓치는 쪽이 훨씬 싸다.
 * 접는·푸는 정본은 `catalyst/power.ts` 의 `readAfterburnerLedger`/`writeAfterburnerLedger`
 * 한 쌍뿐이다(리터럴 16 을 코드에 흩지 마라).
 */
export const enum AfterburnerSlot {
  /** `깎인 최대 HP 누적 * 16 + 대기 전리품 수(0..15)`. */
  Ledger = 23,
}

