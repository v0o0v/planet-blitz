//
// ## 채우는 규약
// 슬롯을 요구하는 카드마다 `const enum` 한 벌을 선언하고, 슬롯 번호가 **동시에 뽑힐 수 있는
// 카드들 사이에서 유일한지**를 보장한다. 스킬 쪽과 달리 "런당 1대" 같은 배타 보장이 없다 —
// 3장이 임의 조합으로 뜨므로, **48종 전역에서 정적으로 유일한 배분표**가 필요하다.
//
// ⚠️ 슬롯 인덱스를 "장착 슬롯 번호(0/1/2)"에서 **동적으로** 배분하지 마라. 같은 카드가 다른
// 슬롯에 꽂힌 두 런이 다른 해시를 내고, 리플레이 재실행이 갈린다.
//
// ## ⭐ 무엇이 슬롯을 **안 먹는가** — 이것을 먼저 걷어내야 폭이 작아진다
// 아래 셋은 슬롯을 한 칸도 쓰지 않는다. 설계가 **일부러** 이렇게 쓴 것이라 저장하면 훅
// 등급이 §B 로 되올라간다.
//
//  1. **적 단위 상태는 `aux0` 다** — `id 1`(강탈) · `id 6`(도금 단계) · `id 15`(실린 액수) ·
//     `id 17`(금빛 액수) · `id 20`(동조) · `id 29`(이동 불능) · `id 36`(그림자) ·
//     점화 약공명(밀려남). 인코딩 정본은 {@link file://./catalystMarks.ts} 다.
//  2. **틱의 순수 파생은 슬롯이 아니다** — `id 33` 안전 원 중심(`mix32(floor(tick/JUMP), SALT)`) ·
//     침식 강공명 반경(`floor(tick/1800)` + `state.wave.segmentIndex`) · `id 12` 누적 비율
//     (현재 최대 HP ÷ 기준 최대 HP) · `id 30` 누진 단계(`segmentIndex`) ·
//     `id 13` 화면 적 수(`countEnemies`) · `id 47` 보스 방어력(남은 블록 수).
//  3. **기존 필드 재해석은 슬롯이 아니다** — 도박 강공명(`state.loot[0]` 의 `rarity` 예약값) ·
//     `id 13`(`bullet.radius`) · `id 2`/정밀 약공명/밀도 강공명(`bullet.pierce`) ·
//     `id 3`(`loot` kind + 등급코드 구간) · `id 12`/`24`/`27`/`29`(`player.maxHp`) ·
//     `id 19`/`21`/`23`/`46`(`destructible` 틀) · `id 44`(보스 페이즈).
//
// ## 공존 규칙 — 어디까지 재사용해도 되는가
//  - **공용끼리는 임의 공존**한다(런당 3장이 30종에서 자유 조합) → 공용은 **전부 유일**.
//  - **특산은 같은 행성끼리만 공존**한다(런은 한 행성에서 벌어지고, 서로 다른 행성 특산
//    2장은 `catalystCapSweep` 이 세는 4,866 불가능 조합에 든다) → **행성 간 재사용 가능**,
//    같은 행성 안에서만 갈린다. 다만 특산은 **공용과 반드시 공존**하므로 공용 구역(0..14)
//    과는 겹치면 안 된다.
//  - **공명은 한 런에 하나만 발동**한다(강 우선, 동급이면 태그 우선순위 — `catalystResonance.ts`
//    의 `resolveResonance` 가 유일 정본) → **공명끼리 재사용 가능**. 단 공명은 카드 3장과
//    항상 함께 있으므로 카드 구역(0..19)과는 겹치면 안 된다.
//
// ## 무촉매 런
// 카드 소지 게이트를 통과하지 못하면 어느 칸도 안 쓰이므로 전 슬롯이 런 끝까지 0 이고
// `hashWorld` 의 촉매 슬롯 폴드가 한 번도 실행되지 않는다(기존 골든 바이트 불변).

